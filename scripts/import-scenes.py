#!/usr/bin/env python3
"""Turns the illustrated scenes (a folder of <name>/code.html, each the base64 of an SVG) into src/genui/deck/art/scenes.ts.

  python3 scripts/import-scenes.py <folder>

Each scene is decoded, its labels removed (the title badge and the text on it: the presentation writes its own words, in
the reader's language), its ids made unique (several scenes can be on one page) and its comments dropped. The output is a
TypeScript module of SVG strings keyed by the id the art catalogue uses ("scene-wind-farm").
"""
import base64, json, os, re, sys

NAMES = {
    'wind_farm_scene': 'scene-wind-farm',
    'solar_roof_scene': 'scene-solar-roof',
    'household_energy_scene': 'scene-household',
    'city_and_industry_scene': 'scene-city-industry',
    'tanker_and_pipeline_scene': 'scene-tanker-pipeline',
    'energy_mix_finale_scene': 'scene-energy-mix',
    'biomass_and_geothermal_scene': 'scene-biomass-geothermal',
    'hydroelectric_dam_scene': 'scene-hydro-dam',
    'oil_pumps_scene': 'scene-oil-pumps',
}

def clean(svg: str, sid: str) -> str:
    # the title badge (rect, text, dot) and the other labels that carry words
    svg = re.sub(r'<!--\s*Title Badge[^>]*-->\s*<rect[^>]*/>\s*<text[\s\S]*?</text>\s*<circle[^>]*/>', '', svg)
    svg = re.sub(r'<!--\s*Station Label Badge\s*-->\s*<rect[^>]*/>', '', svg)
    svg = re.sub(r'<!--[^>]*A\+\+\+[^>]*-->\s*<g>\s*<polygon[^>]*/>[\s\S]*?</g>', '', svg)
    svg = re.sub(r'<g transform="translate\((?:100, 490|60, 480)\)">[\s\S]*?</g>', '', svg)
    svg = re.sub(r'<text[\s\S]*?</text>', '', svg)
    svg = re.sub(r'<!--[\s\S]*?-->', '', svg)
    # ids unique per scene
    ids = re.findall(r'\bid="([^"]+)"', svg)
    for i in ids:
        svg = svg.replace(f'id="{i}"', f'id="{sid}-{i}"').replace(f'url(#{i})', f'url(#{sid}-{i})').replace(f'href="#{i}"', f'href="#{sid}-{i}"')
    svg = svg.replace('<svg ', '<svg preserveAspectRatio="xMidYMid slice" ', 1) if 'preserveAspectRatio' not in svg[:300] else svg
    svg = re.sub(r'>\s+<', '><', svg)
    svg = re.sub(r'\s+', ' ', svg).strip()
    return svg

def main():
    folder = sys.argv[1]
    out = {}
    for name, sid in NAMES.items():
        path = os.path.join(folder, name, 'code.html')
        raw = open(path, 'rb').read().strip()
        svg = base64.b64decode(raw).decode('utf8')
        assert svg.lstrip().startswith('<svg'), name
        out[sid] = clean(svg, sid)
    lines = ['/* Generated by scripts/import-scenes.py from the illustrated scenes: SVG strings keyed by art id. */', 'export const SCENES: Record<string, string> = {']
    for sid, svg in out.items():
        lines.append(f'  {json.dumps(sid)}: {json.dumps(svg)},')
    lines.append('}')
    dest = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'src', 'genui', 'deck', 'art', 'scenes.ts')
    open(dest, 'w', encoding='utf-8').write('\n'.join(lines) + '\n')
    for sid, svg in out.items():
        print(f'{sid}: {len(svg)} chars, text elements left: {svg.count("<text")}')

main()
