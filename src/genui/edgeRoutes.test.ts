// Edge phrasings per dashboard: where each question must go. Custom dashboards (sankey, profile, balance, trade, prices, monthly,
// renewables, reporting, oil), the general dashboard when none fits ("general"), a chat answer ("concept", "answer"), a question
// back ("clarify") or a refusal, in English, German, French, Spanish, Italian, Portuguese, Polish and Dutch, with typos, mixed languages and long sentences. 'a|b' accepts either. Add a case here whenever a question was routed wrongly.
const read = (f: string) => JSON.parse(readFileSync(`public/data/eurostat/energy/${f}`, 'utf8'))
const dict = read('dictionary.json')
const codelists = read('codelists.json')
const { docFreq } = buildKnowledgeIndex(read('knowledge.json').passages)
const scope = createScopeChecker(dict, codelists)
const vocabulary = buildVocabulary(dict, codelists, scope.places)
const unknownWords = (x: string) => vocabulary.unknownWords(x, docFreq)
const correct = (w: string) => vocabulary.correct(w, docFreq)

const kindOf = (r: Route): string => {
  if (r.kind !== 'plan' && r.kind !== 'refine') return r.kind
  const p = r.plan
  if (p.sankey) return 'sankey'
  if (p.profile) return 'profile'
  if (p.prices) return 'prices'
  if (p.trade) return 'trade'
  if (p.balance) return 'balance'
  if (p.oil) return 'oil'
  if (p.renewables) return 'renewables'
  if (p.reporting) return 'reporting'
  return /^nrg_(cb_(pem|gas|oil|sff)m|cb_cosm|stk_oilm|ti_(gas|oil)m)|nrg_cb_\w+m$/.test(p.dataset) || p.filters?.freq === 'M' ? 'monthly' : 'general'
}

function route(q: string): string {
  const text = prepareQuestion(q, { unknownWords, correct })
  const verdict = scope.classify(text, [])
  if (verdict !== 'small-talk' && conceptAnswer([q, text], questionLanguage(q, 'en'))) return 'concept'
  return kindOf(routeMessage(text, { current: null, dict, codelists, classify: () => verdict, unknownWords, correct, previous: [] }))
}

