test('every way of asking reaches its view', () => {
  const wrong: string[] = []
  for (const [expected, q] of PHRASINGS) {
    const got = view(q)
    const ok = expected.split('/').some((e) => (e.endsWith('*') ? got.startsWith(e.slice(0, -1)) : got === e))
    if (!ok) wrong.push(`${q}
    expected ${expected}, got ${got}`)
  }
  assert.deepEqual(wrong, [])
})
